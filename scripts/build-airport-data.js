#!/usr/bin/env node
// Regenerates tools/itinerary/preview/src/airport_data.rs. Run it with `nix run .#airports`.
//
// The link preview card shows a trip's route as cities, but a leg's from and
// to are whatever was typed: an airport code, or an airport's name, "Chicago
// O'Hare". For every airport with scheduled service, this maps both its code
// and its name to the city OurAirports names for it.
//
// A name is matched exactly, after both sides lose case, apostrophes, and any
// of TRAILING_WORDS at the end, so "Chicago O'Hare" matches "Chicago O'Hare
// International Airport". A name left to more than one city is dropped.
//
// OurAirports' municipality is sometimes more than a city: "Helsinki
// (Vantaa)", "Birmingham, West Midlands", "Santa Cruz/Graciosa Bay/Luova".
// Only the part before the first parenthesis, comma or slash is kept.

import { writeFile } from "node:fs/promises";

const SOURCE = "https://davidmegginson.github.io/ourairports-data/airports.csv";
const OUT = new URL("../tools/itinerary/preview/src/airport_data.rs", import.meta.url);

// Words that may end an airport's name without changing which airport it is.
// src/route.rs reads this list from the generated file, so both sides chop the
// same words.
const TRAILING_WORDS = ["international", "intl", "airport", "airfield", "aerodrome", "regional"];

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`${SOURCE} returned ${res.status}`);
const [header, ...records] = parseCsv(await res.text());

const column = (name) => {
  const index = header.indexOf(name);
  if (index < 0) throw new Error(`${SOURCE} has no ${name} column`);
  return index;
};
const IATA = column("iata_code");
const NAME = column("name");
const CITY = column("municipality");
const SCHEDULED = column("scheduled_service");

const byCode = new Map();
const byName = new Map();
for (const record of records) {
  const code = (record[IATA] ?? "").trim();
  const city = (record[CITY] ?? "").split(/\s*[(,/]/)[0].trim();
  if (record[SCHEDULED] !== "yes" || !/^[A-Z]{3}$/.test(code) || !city) continue;
  if (byCode.has(code)) throw new Error(`${code} appears twice among scheduled airports`);
  byCode.set(code, city);

  const name = nameKey(record[NAME] ?? "");
  if (!name) continue;
  if (!byName.has(name)) byName.set(name, new Set());
  byName.get(name).add(city);
}

const sorted = (entries) => [...entries].sort(([a], [b]) => (a < b ? -1 : 1));
const codes = sorted(byCode);
const names = sorted([...byName].filter(([, cities]) => cities.size === 1).map(([name, cities]) => [name, [...cities][0]]));
const pairs = (rows) => rows.map(([key, city]) => `    (${JSON.stringify(key)}, ${JSON.stringify(city)}),`);

const lines = [
  "// GENERATED by scripts/build-airport-data.js from OurAirports (public domain). Rebuild with",
  "// `nix run .#airports`; do not edit by hand.",
  "",
  "/// Words chopped off the end of a place before it is compared with `AIRPORT_NAMES`.",
  `pub static TRAILING_WORDS: &[&str] = &[${TRAILING_WORDS.map((w) => JSON.stringify(w)).join(", ")}];`,
  "",
  "/// IATA code to city, for every airport with scheduled service, sorted by code.",
  "pub static AIRPORT_CITIES: &[(&str, &str)] = &[",
  ...pairs(codes),
  "];",
  "",
  "/// Airport name, lowercase, without apostrophes or trailing words, to city, sorted by name. Names that",
  "/// belong to more than one city are left out.",
  "pub static AIRPORT_NAMES: &[(&str, &str)] = &[",
  ...pairs(names),
  "];",
  "",
];
await writeFile(OUT, lines.join("\n"));
console.log(`Wrote ${codes.length} codes and ${names.length} names to ${OUT.pathname}`);

// Lowercase, apostrophes dropped, every other run of anything but letters and
// digits a single space, and trailing words removed. src/route.rs does the same.
function nameKey(name) {
  const words = name
    .toLowerCase()
    .replace(/['’]/g, "")
    .split(/[^\p{L}\p{N}]+/u)
    .filter(Boolean);
  while (words.length && TRAILING_WORDS.includes(words.at(-1))) words.pop();
  return words.join(" ");
}

// RFC 4180: fields may be quoted, and quoted fields may hold commas, newlines
// and doubled quotes.
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') {
        quoted = false;
      } else {
        field += c;
      }
    } else if (c === '"') {
      quoted = true;
    } else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else {
      field += c;
    }
  }
  if (field || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}
